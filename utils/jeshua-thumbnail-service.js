const fs = require('fs').promises;
const path = require('path');
const { BRAND, createThumbnailPlan, buildThumbnailPlan } = require('./jeshua-thumbnail-plan');
const { renderThumbnail, assertCopyFits } = require('./jeshua-thumbnail-renderer');

function isJeshuaStyle(env = process.env) {
  if (env.THUMBNAIL_STYLE) return env.THUMBNAIL_STYLE === BRAND.id;
  // 05/10/2026: the brand went from "Jeshua" to "Yeshua"; both are accepted.
  return /^oraciones en presencia de [jy]eshua$/.test(
    String(env.CHANNEL_NAME || '').normalize('NFD').replace(/[\u0300-\u036f]/g, '').trim().toLowerCase());
}

function inputFromScript(script) {
  return {
    video_title: script.title, video_topic: script.metadata?.strategy?.topic,
    video_summary: script.summary || script.description,
    script, bible_verse: script.scriptures,
    prayer_type: script.prayer_type || script.prayerType,
    emotion: script.emotion, time_of_day: script.time_of_day || script.timeOfDay,
    language: script.language || script.metadata?.language || process.env.CONTENT_LANGUAGE || 'es',
  };
}

class JeshuaThumbnailService {
  constructor({ aiTextService = null, imageGenerator = null } = {}) {
    this.aiTextService = aiTextService;
    this.imageGenerator = imageGenerator;
  }

  async create(input, {
    outputDir, artworkPath = null, generate = false, planOnly = false,
    variants = 1, startVariant = 0, approveArtwork = false, textSide = 'auto', subjectRegion = null,
  } = {}) {
    if (!Number.isInteger(variants) || variants < 1 || variants > 4) throw new Error('variants must be an integer from 1 to 4.');
    if (!Number.isSafeInteger(startVariant) || startVariant < 0 || !Number.isSafeInteger(startVariant + variants)) throw new Error('startVariant must be a non-negative safe integer.');
    if (!outputDir) throw new Error('An output directory is required.');
    if (generate && artworkPath) throw new Error('Choose supplied artwork or remote generation, not both.');
    if (planOnly && generate) throw new Error('planOnly cannot be combined with remote generation.');
    if (!planOnly && !artworkPath && !generate) throw new Error('Supply artworkPath or explicitly enable generate.');
    if (generate && !this.imageGenerator) throw new Error('No image generation provider configured. Supply artworkPath or configure an image provider.');
    if (approveArtwork && !artworkPath) throw new Error('Only already inspected supplied artwork can be marked operator-confirmed.');
    if (artworkPath) await fs.access(artworkPath);
    await fs.mkdir(outputDir, { recursive: true });
    const runDir = await fs.mkdtemp(path.join(path.resolve(outputDir), 'jeshua-'));
    const result = { brandId: BRAND.id, createdAt: new Date().toISOString(), mode: planOnly ? 'plan' : generate ? 'generated' : 'supplied-artwork', variants: [] };
    for (let index = 0; index < variants; index++) {
      // Offline modes do not call either provider, even when credentials exist.
      let plan = await createThumbnailPlan(input, { variant: startVariant + index, aiTextService: generate ? this.aiTextService : null });
      // Reject or reframe copy before paying for artwork. The same real font
      // measurements are used here and by the final renderer.
      if (!planOnly) {
        try { await assertCopyFits(plan); }
        catch (error) {
          if (plan.source !== 'ai') throw error;
          plan = buildThumbnailPlan(input, { variant: startVariant + index });
          plan.generation = { ...plan.generation, ai_attempted: true, fallback_reason: 'AI copy could not fit at a readable mobile size.' };
          await assertCopyFits(plan);
        }
      }
      const variantDir = path.join(runDir, `variant-${index + 1}`);
      await fs.mkdir(variantDir);
      const planPath = path.join(variantDir, 'plan.json');
      await fs.writeFile(planPath, JSON.stringify(plan, null, 2));
      const item = { plan, planPath };
      if (!planOnly) {
        let source = artworkPath;
        if (generate) {
          source = path.join(variantDir, 'artwork.png');
          // One distinct artwork per variant, with no lettering generated by AI.
          await this.imageGenerator.generateImage(`${plan.image_generation_prompt}\nAvoid: ${plan.negative_prompt}`, source);
        }
        Object.assign(item, await renderThumbnail({
          plan, artworkPath: source, outputDir: variantDir, approveArtwork,
          textSide: generate ? plan.composition.text_side : textSide,
          subjectRegion: generate ? plan.subject_region : subjectRegion,
        }));
      }
      result.variants.push(item);
    }
    result.manifestPath = path.join(runDir, 'manifest.json');
    await fs.writeFile(result.manifestPath, JSON.stringify(result, null, 2));
    return result;
  }
}

module.exports = { JeshuaThumbnailService, isJeshuaStyle, inputFromScript };
